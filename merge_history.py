def parse_tdx_file(filepath):
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()
    js = content[content.find("{"):]
    data = json.loads(js)
    klines = []
    for item in data["ListItem"]:
        v = item["Item"]
        klines.append({
            "date": v[0], "open": float(v[2]), "high": float(v[3]),
            "low": float(v[4]), "close": float(v[5]), "volume": float(v[8]),
        })
    return klines

def main():
    all_klines = {}
    for key, fp in FILES.items():
        ks = parse_tdx_file(fp)
        for k in ks:
            all_klines[k["date"]] = k
        print(f"  {key}: {len(ks)}根")
    # 加入内联46根
    for row in XH1500_INLINE:
        all_klines[row[0]] = {"date": row[0], "open": row[1], "high": row[2],
                              "low": row[3], "close": row[4], "volume": float(row[5])}
    print(f"  xh1500(inline): {len(XH1500_INLINE)}根")

    # 按日期排序
    sorted_klines = sorted(all_klines.values(), key=lambda x: x["date"])
    out = os.path.join(BASE, "history_klines.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(sorted_klines, f, ensure_ascii=False, indent=1)
    print(f"\n合并完成: {len(sorted_klines)}根 ({sorted_klines[0]['date']} ~ {sorted_klines[-1]['date']})")
    print(f"已保存: {out}")

if __name__ == "__main__":
    main()
